package gnolang

import (
	"fmt"
	"testing"
)

// sf2: cost of the runtime method-signature check in VerifyImplementedBy,
// head (identicalTypes) vs merge base (cached TypeID string compare).
func sf2Sig(n int) *FuncType {
	fs := make([]FieldType, n)
	for i := range fs {
		fs[i] = FieldType{Name: Name(fmt.Sprintf("F%d", i)), Type: IntType}
	}
	st := &StructType{PkgPath: "gno.land/r/x", Fields: fs}
	return &FuncType{Params: []FieldType{{Name: "s", Type: st}}}
}

func TestSF2IdentityCost(t *testing.T) {
	for _, n := range []int{1, 100, 1000, 10000} {
		a, b := sf2Sig(n), sf2Sig(n)
		_, _ = a.TypeID(), b.TypeID() // cached, as at runtime
		head := testing.Benchmark(func(bb *testing.B) {
			for i := 0; i < bb.N; i++ {
				if !identicalTypes(a, b) {
					bb.Fatal("not identical")
				}
			}
		})
		base := testing.Benchmark(func(bb *testing.B) {
			for i := 0; i < bb.N; i++ {
				if a.TypeID() != b.TypeID() {
					bb.Fatal("not equal")
				}
			}
		})
		t.Logf("fields=%5d head identicalTypes=%10d ns/op  base TypeID==%8d ns/op  ratio=%.1fx",
			n, head.NsPerOp(), base.NsPerOp(), float64(head.NsPerOp())/float64(max(base.NsPerOp(), 1)))
	}
}
